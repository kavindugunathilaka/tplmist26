#!/usr/bin/env python3
"""
Download up to 10 freely licensed photos per trip location from Wikimedia Commons.

  python3 scripts/fetch-place-photos.py            # from the repo root
  python3 scripts/fetch-place-photos.py --per 8    # fewer per place

Writes:
  images/places/<place-id>-<n>.jpg   (1280 px wide)
  images/places/credits.js           (author + licence for each photo; index.html reads it)

Only photos under CC0, public domain, CC BY or CC BY-SA are kept, and the site shows
the credit for each one. Re-running it skips photos that are already downloaded.
No third-party packages are needed.
"""
import argparse, html, json, os, re, sys, time, urllib.parse, urllib.request

API = "https://commons.wikimedia.org/w/api.php"
UA = "Into-the-Mist-trip-site/1.0 (https://github.com/kavindugunathilaka/tplmist26)"
OK_LICENCE = re.compile(r"^(cc0|public domain|pd\b|cc by(-sa)? [\d.]+)", re.I)

# place id (must match index.html) -> Commons search queries, tried in order
PLACES = {
    "ramboda":  ["Ramboda Falls", "Ramboda"],
    "teaf":     ["Labookellie", "Bluefield tea", "Nuwara Eliya tea factory", "tea plantation Nuwara Eliya"],
    "nuwara":   ["Nuwara Eliya"],
    "gregory":  ["Gregory Lake", "Lake Gregory Nuwara Eliya"],
    "horton":   ["Horton Plains", "World's End Sri Lanka", "Baker's Falls"],
    "nzfarm":   ["Ambewela", "Ambewela farm"],
    "kandeela": ["Kande Ela", "Kandapola"],
    "bomburu":  ["Bomburu Ella", "Bomburuella"],
    "shop":     ["Nuwara Eliya market", "Nuwara Eliya town", "Nuwara Eliya post office"],
}

def get(url, params=None, binary=False):
    if params:
        url += "?" + urllib.parse.urlencode(params)
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=40) as r:
                data = r.read()
                return data if binary else json.loads(data)
        except urllib.error.HTTPError as e:
            if e.code == 429 and attempt < 3:
                time.sleep(5 * (attempt + 1)); continue
            raise

def strip(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s or "")).strip()

def search(query, limit=40):
    res = get(API, {
        "action": "query", "format": "json", "generator": "search",
        "gsrsearch": f"{query} filetype:bitmap", "gsrnamespace": 6, "gsrlimit": limit,
        "prop": "imageinfo", "iiprop": "url|extmetadata|size|mime", "iiurlwidth": 1280,
        "iiextmetadatafilter": "Artist|LicenseShortName|LicenseUrl",
    })
    pages = sorted((res.get("query") or {}).get("pages", {}).values(), key=lambda p: p.get("index", 0))
    for p in pages:
        info = (p.get("imageinfo") or [{}])[0]
        meta = info.get("extmetadata", {})
        lic = strip(meta.get("LicenseShortName", {}).get("value"))
        if info.get("mime") != "image/jpeg" or info.get("width", 0) < 800 or not OK_LICENCE.match(lic):
            continue
        yield {
            "title": p["title"],
            "thumb": info.get("thumburl") or info["url"],
            "page": info.get("descriptionurl", ""),
            "artist": strip(meta.get("Artist", {}).get("value")) or "Unknown",
            "licence": lic,
        }

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per", type=int, default=10)
    args = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(root, "images", "places")
    os.makedirs(out, exist_ok=True)
    credits = {}
    for pid, queries in PLACES.items():
        seen, items = set(), []
        for q in queries:
            if len(items) >= args.per: break
            try:
                for it in search(q):
                    if it["title"] in seen: continue
                    seen.add(it["title"]); items.append(it)
                    if len(items) >= args.per: break
            except Exception as e:
                print(f"  ! search '{q}' failed: {e}", file=sys.stderr)
            time.sleep(1)
        credits[pid] = []
        for n, it in enumerate(items, 1):
            fn = f"{pid}-{n}.jpg"; path = os.path.join(out, fn)
            if not os.path.exists(path):
                try:
                    with open(path, "wb") as f: f.write(get(it["thumb"], binary=True))
                    time.sleep(0.5)
                except Exception as e:
                    print(f"  ! download failed {it['title']}: {e}", file=sys.stderr); continue
            credits[pid].append({"src": f"images/places/{fn}",
                                 "credit": f"{it['artist']} · {it['licence']} · Wikimedia Commons",
                                 "page": it["page"]})
        print(f"{pid:9s} {len(credits[pid])} photos")
    with open(os.path.join(out, "credits.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/fetch-place-photos.py. Photos from Wikimedia Commons.\n")
        f.write("window.PLACE_PHOTOS = " + json.dumps(credits, ensure_ascii=False, indent=1) + ";\n")
    print(f"\nDone. Credits written to {os.path.relpath(out, root)}/credits.js")

if __name__ == "__main__":
    main()
